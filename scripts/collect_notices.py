#!/usr/bin/env python3
"""Reproduce distribution notices from installed Go and browser dependencies."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
NOTICE_NAME = re.compile(r"^(license|licence|notice|copying|copyright|patents)(?:[._-]|$)", re.I)
BROWSER_PACKAGES = ("react", "react-dom", "scheduler", "lucide-react", "pdfjs-dist")


def json_stream(text: str):
    decoder = json.JSONDecoder()
    offset = 0
    while offset < len(text):
        while offset < len(text) and text[offset].isspace():
            offset += 1
        if offset == len(text):
            break
        value, offset = decoder.raw_decode(text, offset)
        yield value


def run_go(go: str, *args: str) -> str:
    result = subprocess.run([go, *args], cwd=ROOT, check=True, capture_output=True, encoding="utf-8")
    return result.stdout


def notice_files(directory: Path, recursive: bool = False):
    candidates = directory.rglob("*") if recursive else directory.iterdir()
    return sorted(path for path in candidates if path.is_file() and NOTICE_NAME.match(path.name)
                  and path.suffix.lower() not in {".go", ".c", ".h", ".js", ".ts"})


def read_text(path: Path) -> str:
    # Upstream license text is kept intact, apart from portable LF line endings.
    return path.read_text(encoding="utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")


def collect(go: str, modules_path: Path | None, go_root: Path | None) -> str:
    if modules_path is None:
        # Fresh source checkouts do not need a hand-created work/modules.json.
        run_go(go, "mod", "download")
        modules_text = run_go(go, "list", "-m", "-json", "all")
    else:
        modules_text = read_text(modules_path)
    modules = sorted((module for module in json_stream(modules_text) if not module.get("Main")),
                     key=lambda module: module["Path"])
    if go_root is None:
        go_root = Path(run_go(go, "env", "GOROOT").strip())
    go_version = read_text(go_root / "VERSION").splitlines()[0]
    sections: list[str] = []

    def add(component: str, base: Path, paths: list[Path]):
        if not paths:
            raise ValueError(f"No upstream license found for {component}")
        for path in paths:
            label = path.relative_to(base).as_posix()
            sections.append("=" * 78 + f"\n{component}\nUpstream file: {label}\n" + "=" * 78 + "\n\n" + read_text(path).rstrip() + "\n")

    add(f"Go toolchain and standard library ({go_version})", go_root, notice_files(go_root))
    # Include the standard library's own embedded/vendor notices, not compiler
    # tooling and test fixtures which are not in the shipped service executable.
    std_notices = [path for path in notice_files(go_root / "src", recursive=True)
                   if "testdata" not in path.relative_to(go_root / "src").parts
                   and path.relative_to(go_root / "src").parts[0] != "cmd"]
    add(f"Go standard library third-party notices ({go_version})", go_root, std_notices)

    for module in modules:
        source = module.get("Replace", module)
        if not source.get("Dir"):
            # go list can omit Dir for lazily loaded graph-only dependencies.
            downloaded = json.loads(run_go(go, "mod", "download", "-json", source["Path"] + "@" + source["Version"]))
            if downloaded.get("Error") or not downloaded.get("Dir"):
                raise ValueError(f"Cannot read source notices for {module['Path']}")
            source = {**source, "Dir": downloaded["Dir"]}
        directory = Path(source["Dir"])
        add(f"Go module: {module['Path']} {module.get('Version', '(local)')}", directory, notice_files(directory))

    for name in BROWSER_PACKAGES:
        directory = ROOT / "web" / "node_modules" / name
        metadata = json.loads(read_text(directory / "package.json"))
        add(f"Browser dependency: {name} {metadata['version']}", directory, notice_files(directory))
        if name == "pdfjs-dist":
            # These folders are shipped by copy-pdf-assets.mjs, including the
            # JavaScript decoder fallbacks and all corresponding license files.
            for folder in ("cmaps", "standard_fonts", "iccs", "wasm"):
                add(f"PDF.js asset notices: {folder} ({metadata['version']})", directory,
                    notice_files(directory / folder, recursive=True))

    header = """SynoFind - Third-Party Software Notices

Generated by scripts/collect_notices.py from the installed, locked dependencies.
The following upstream copyright, license, attribution and patent notices are
reproduced for redistribution with the SynoFind executable and web application.

Scope: the Go runtime/standard library and selected Go module graph, plus the
browser runtime dependencies React, React DOM, Scheduler, Lucide and PDF.js.
The module graph and upstream aggregate notices may also name build/test-only
components; their inclusion does not assert that they are linked into SynoFind.
PDF.js CMaps, fonts, ICC profiles and JavaScript decoder fallback resources retain
their individual notices below and alongside the distributed resource files.
The optional Node-only canvas dependency and unshipped QuickJS/WASM binaries are
not used by SynoFind's browser viewer. Upstream license files for the shipped
PDF.js asset folders are retained in full even where they cover additional files.

SynoFind's own source license, if provided, is separate. No third-party license
is replaced or modified by this notice aggregation.

"""
    return header + "\n".join(sections)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    portable_go = ROOT / ".tools" / "go" / "bin" / ("go.exe" if os.name == "nt" else "go")
    parser.add_argument("--go-path", default=str(portable_go) if portable_go.exists() else "go")
    parser.add_argument("--go-root", type=Path)
    parser.add_argument("--modules", type=Path, help="Optional pre-generated go list -m -json all stream")
    args = parser.parse_args()
    content = collect(args.go_path, args.modules, args.go_root)
    target = ROOT / "docs" / "THIRD_PARTY_NOTICES.txt"
    target.write_text(content, encoding="utf-8", newline="\n")
    package_target = ROOT / "packaging" / "payload" / "THIRD_PARTY_NOTICES.txt"
    shutil.copyfile(target, package_target)
    print(f"Collected notices: {len(content.encode('utf-8'))} bytes; docs and SPK payload copies match.")


if __name__ == "__main__":
    main()
